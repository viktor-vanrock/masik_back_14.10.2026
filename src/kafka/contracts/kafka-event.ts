/**
 * Общая оболочка всех интеграционных Kafka-событий.
 *
 * Kafka передаёт только bytes. Эта структура задаёт наш договор:
 * какие служебные поля должны присутствовать в каждом JSON-сообщении.
 */
export type KafkaEvent<
  TType extends string,
  TData,
  TVersion extends number = 1
> = Readonly<{
  /**
   * Уникальный идентификатор конкретного события.
   *
   * При повторной доставке eventId не меняется.
   * По нему consumer позднее будет проверять inbox и отбрасывать дубли.
   */
  eventId: string;

  /**
   * Машиночитаемое название события.
   * Позволяет различать несколько типов сообщений в одном topic.
   */
  eventType: TType;

  /**
   * Версия структуры сообщения.
   * При несовместимом изменении контракта создаётся новая версия topic/event.
   */
  eventVersion: TVersion;

  /**
   * Время создания события в UTC, ISO 8601.
   */
  occurredAt: string;

  /**
   * Бизнес-данные конкретного события.
   */
  data: Readonly<TData>;
}>;
