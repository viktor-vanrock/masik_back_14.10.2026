import {
  Body,
  Controller,
  Get,
  HttpCode,
  HttpStatus,
  Param,
  Post,
  Query,
  UseGuards,
} from '@nestjs/common';
import {
  ApiCreatedResponse,
  ApiHeader,
  ApiOkResponse,
  ApiOperation,
  ApiSecurity,
  ApiTags,
} from '@nestjs/swagger';
import { CsrfExempt } from '@/common/decorators/csrf-exempt.decorator';
import { Public } from '@/common/decorators/public.decorator';
import { PaginationDto } from '@/common/dtos/paginationDto.dto';
import { CreateMetricResultDto } from '@/metrics/dto/create-metric-result.dto';
import { MetricsService } from '@/metrics/metrics.service';
import { ExternalApiScopes } from '../api-keys/decorators/external-api-scopes.decorator';
import { EXTERNAL_API_KEY_SCOPE } from '../api-keys/external-api-key.constants';
import { ExternalApiKeyGuard } from '../api-keys/guards/external-api-key.guard';

@ApiTags('external-metric-results')
@ApiSecurity('x-api-key')
@ApiHeader({
  name: 'x-api-key',
  description: 'External API key generated by an internal administrator.',
  required: true,
})
@Public()
@UseGuards(ExternalApiKeyGuard)
@Controller('external/v1')
export class ExternalMetricResultsController {
  constructor(private readonly metricsService: MetricsService) {}

  @Get('benchmark-tests/:testId/metric-results')
  @ExternalApiScopes(EXTERNAL_API_KEY_SCOPE.METRIC_RESULTS_READ)
  @ApiOperation({ summary: 'Get metric results by benchmark test id' })
  @ApiOkResponse({
    description: 'Paginated metric results for the benchmark test.',
  })
  findMetricResultsByTestId(
    @Param('testId') testId: string,
    @Query() queryParams: PaginationDto
  ) {
    return this.metricsService.findMetricResultsByTestId(
      testId,
      queryParams
    );
  }

  @Post('metric-results')
  @CsrfExempt()
  @HttpCode(HttpStatus.CREATED)
  @ExternalApiScopes(EXTERNAL_API_KEY_SCOPE.METRIC_RESULTS_WRITE)
  @ApiOperation({
    summary: 'Create metric result',
    description:
      'Creates a score for an existing benchmark test, metric definition and model.',
  })
  @ApiCreatedResponse({ description: 'Metric result created.' })
  createMetricResult(@Body() body: CreateMetricResultDto) {
    return this.metricsService.createMetricResult(body);
  }
}
