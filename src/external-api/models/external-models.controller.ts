import {
  Body,
  Controller,
  Get,
  HttpCode,
  HttpStatus,
  Post,
  UseGuards,
} from '@nestjs/common';
import {
  ApiCreatedResponse,
  ApiHeader,
  ApiOkResponse,
  ApiOperation,
  ApiSecurity,
  ApiTags,
} from '@nestjs/swagger';
import { CsrfExempt } from '@/common/decorators/csrf-exempt.decorator';
import { Public } from '@/common/decorators/public.decorator';
import { CreateModelDto } from '@/metrics/dto/create-model.dto';
import { MetricsService } from '@/metrics/metrics.service';
import { ExternalApiScopes } from '../api-keys/decorators/external-api-scopes.decorator';
import { EXTERNAL_API_KEY_SCOPE } from '../api-keys/external-api-key.constants';
import { ExternalApiKeyGuard } from '../api-keys/guards/external-api-key.guard';

@ApiTags('external-models')
@ApiSecurity('x-api-key')
@ApiHeader({
  name: 'x-api-key',
  description: 'External API key generated by an internal administrator.',
  required: true,
})
@Public()
@UseGuards(ExternalApiKeyGuard)
@Controller('external/v1/models')
export class ExternalModelsController {
  constructor(private readonly metricsService: MetricsService) {}

  @Get()
  @ExternalApiScopes(EXTERNAL_API_KEY_SCOPE.MODELS_READ)
  @ApiOperation({ summary: 'Get models used in metric results' })
  @ApiOkResponse({ description: 'Models list.' })
  findAllModels() {
    return this.metricsService.findAllModels();
  }

  @Post()
  @CsrfExempt()
  @HttpCode(HttpStatus.CREATED)
  @ExternalApiScopes(EXTERNAL_API_KEY_SCOPE.MODELS_WRITE)
  @ApiOperation({
    summary: 'Create or update model',
    description:
      'Upserts a model by its external string id. Repeating the request updates its metadata.',
  })
  @ApiCreatedResponse({ description: 'Model created or updated.' })
  createModel(@Body() body: CreateModelDto) {
    return this.metricsService.createModel(body);
  }
}
