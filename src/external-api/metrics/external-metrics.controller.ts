import {
  Body,
  Controller,
  Get,
  HttpCode,
  HttpStatus,
  Param,
  ParseUUIDPipe,
  Post,
  Query,
  UseGuards,
} from '@nestjs/common';
import {
  ApiCreatedResponse,
  ApiHeader,
  ApiOkResponse,
  ApiOperation,
  ApiSecurity,
  ApiTags,
} from '@nestjs/swagger';
import { CsrfExempt } from '@/common/decorators/csrf-exempt.decorator';
import { Public } from '@/common/decorators/public.decorator';
import { PaginationDto } from '@/common/dtos/paginationDto.dto';
import { CreateMetricDefinitionDto } from '@/metrics/dto/create-metric-definition.dto';
import { MetricsService } from '@/metrics/metrics.service';
import { ExternalApiScopes } from '../api-keys/decorators/external-api-scopes.decorator';
import { EXTERNAL_API_KEY_SCOPE } from '../api-keys/external-api-key.constants';
import { ExternalApiKeyGuard } from '../api-keys/guards/external-api-key.guard';

@ApiTags('external-metrics')
@ApiSecurity('x-api-key')
@ApiHeader({
  name: 'x-api-key',
  description: 'External API key generated by an internal administrator.',
  required: true,
})
@Public()
@UseGuards(ExternalApiKeyGuard)
@Controller('external/v1/metrics')
export class ExternalMetricsController {
  constructor(private readonly metricsService: MetricsService) {}

  @Get('lookups/priorities')
  @ExternalApiScopes(EXTERNAL_API_KEY_SCOPE.METRIC_DEFINITIONS_READ)
  @ApiOperation({
    summary: 'Get metric priority lookup values',
    description:
      'Returns priority identifiers required to create metric definitions.',
  })
  @ApiOkResponse({ description: 'Metric priority lookup values.' })
  findAllPriorities() {
    return this.metricsService.findAllPriorities();
  }

  @Get('lookups/directions')
  @ExternalApiScopes(EXTERNAL_API_KEY_SCOPE.METRIC_DEFINITIONS_READ)
  @ApiOperation({
    summary: 'Get metric direction lookup values',
    description:
      'Returns direction identifiers required to create metric definitions.',
  })
  @ApiOkResponse({ description: 'Metric direction lookup values.' })
  findAllDirections() {
    return this.metricsService.findAllDirections();
  }

  @Get()
  @ExternalApiScopes(EXTERNAL_API_KEY_SCOPE.METRIC_DEFINITIONS_READ)
  @ApiOperation({ summary: 'Get metric definitions' })
  @ApiOkResponse({ description: 'Paginated metric definitions.' })
  findAllMetrics(@Query() queryParams: PaginationDto) {
    return this.metricsService.findAllMetrics(queryParams);
  }

  @Get(':id')
  @ExternalApiScopes(EXTERNAL_API_KEY_SCOPE.METRIC_DEFINITIONS_READ)
  @ApiOperation({ summary: 'Get metric definition by id' })
  @ApiOkResponse({ description: 'Metric definition.' })
  findMetricById(
    @Param('id', new ParseUUIDPipe()) id: string
  ) {
    return this.metricsService.findMetricById(id);
  }

  @Post()
  @CsrfExempt()
  @HttpCode(HttpStatus.CREATED)
  @ExternalApiScopes(EXTERNAL_API_KEY_SCOPE.METRIC_DEFINITIONS_WRITE)
  @ApiOperation({
    summary: 'Create metric definition',
    description:
      'Creates a metric definition. Fetch priority and direction ids from the lookup endpoints first.',
  })
  @ApiCreatedResponse({ description: 'Metric definition created.' })
  createMetric(@Body() body: CreateMetricDefinitionDto) {
    return this.metricsService.createMetric(body);
  }
}
