import {
  Body,
  Controller,
  Get,
  HttpCode,
  HttpStatus,
  Param,
  Post,
  UseGuards,
} from '@nestjs/common';
import {
  ApiHeader,
  ApiOkResponse,
  ApiOperation,
  ApiSecurity,
  ApiTags,
} from '@nestjs/swagger';
import { CsrfExempt } from '@/common/decorators/csrf-exempt.decorator';
import { Public } from '@/common/decorators/public.decorator';
import { ExternalApiScopes } from '../api-keys/decorators/external-api-scopes.decorator';
import { EXTERNAL_API_KEY_SCOPE } from '../api-keys/external-api-key.constants';
import { ExternalApiKeyGuard } from '../api-keys/guards/external-api-key.guard';
import { ExternalBenchmarkTestListResponseDto, ExternalBenchmarkTestDto } from './dto/externalBenchmarkTestResponseDto.dto';
import { ExternalBenchmarkTestSearchDto } from './dto/externalBenchmarkTestSearchDto.dto';
import { ExternalAvailableFieldsResponseDto, ExternalFieldValuesResponseDto } from './dto/externalFieldValuesResponseDto.dto';
import { ExternalBenchmarkTestsService } from './external-benchmark-tests.service';

@ApiTags('external-benchmark-tests')
@ApiSecurity('x-api-key')
@ApiHeader({
  name: 'x-api-key',
  description: 'External API key generated by internal admins.',
  required: true,
})
@Public()
@ExternalApiScopes(EXTERNAL_API_KEY_SCOPE.BENCHMARK_TESTS_READ)
@UseGuards(ExternalApiKeyGuard)
@Controller('external/v1/benchmark-tests')
export class ExternalBenchmarkTestsController {
  constructor(
    private readonly benchmarkTestsService: ExternalBenchmarkTestsService
  ) {}

  @Post('search')
  @HttpCode(HttpStatus.OK)
  @CsrfExempt()
  @ApiOperation({
    summary: 'Search benchmark tests for external services',
    description:
      'Filters BenchmarkTest records by provided non-null fields. Empty arrays, null and undefined values are ignored.',
  })
  @ApiOkResponse({ type: ExternalBenchmarkTestListResponseDto })
  async search(
    @Body() body: ExternalBenchmarkTestSearchDto
  ): Promise<ExternalBenchmarkTestListResponseDto> {
    return this.benchmarkTestsService.search(body);
  }

  @Get('fields')
  @ApiOperation({
    summary: 'Get available filter fields',
    description:
      'Returns whitelist of fields supported by field-values endpoint.',
  })
  @ApiOkResponse({ type: ExternalAvailableFieldsResponseDto })
  getAvailableFields(): ExternalAvailableFieldsResponseDto {
    return this.benchmarkTestsService.getAvailableFields();
  }

  @Get('fields/:field/values')
  @ApiOperation({
    summary: 'Get distinct non-null values for field',
    description:
      'Returns all unique existing values for supported BenchmarkTest scalar or relation field.',
  })
  @ApiOkResponse({ type: ExternalFieldValuesResponseDto })
  async getFieldValues(
    @Param('field') field: string
  ): Promise<ExternalFieldValuesResponseDto> {
    return this.benchmarkTestsService.getFieldValues(field);
  }

  @Get(':id')
  @ApiOperation({
    summary: 'Get external benchmark test by id',
    description:
      'Returns one BenchmarkTest in external API format: benchmark, taxonomy, metrics, gigaMetrics and links.',
  })
  @ApiOkResponse({ type: ExternalBenchmarkTestDto })
  async findById(
    @Param('id') id: string
  ): Promise<ExternalBenchmarkTestDto> {
    return this.benchmarkTestsService.findById(id);
  }
}
